"""Code for the code index: a source file, a repo's doc or a notebook, cut into stretches of whole lines (a notebook's
into whole cells), each knowing where it is, so a result opens there. And names: a query that's a name finds the
place that defines it rather than every place that uses it."""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path

from . import rules
from .model import IndexOptions

LONGEST_PIECE = 4000
# A real key: the armor line followed by its base64 body (code that only mentions the marker is fine).
PRIVATE_KEY = re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----\s*[A-Za-z0-9+/=\s]{64,}")
CLOSERS = {"end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"}


class LeftOut(Exception):
    """Not for the index after all, once read (a program wrote it, or it holds a private key)."""


@dataclass
class Piece:
    text: str
    first: int
    last: int


@dataclass
class CodeFile:
    pieces: list[Piece]
    title: str
    repo: str | None
    lines: int
    cells: int | None


def read(path: str, options: IndexOptions) -> CodeFile:
    data = Path(path).read_bytes()
    repo, title = place(path)
    if rules.ext_of(path) == "ipynb":
        cells = notebook_cells(data)
        text = "\n".join(cells)
        if len(text.encode()) > options.max_code_bytes:
            raise LeftOut(f"cells over {options.max_code_bytes >> 20} MB")
        check(text, source=True)
        return CodeFile(cells_to_pieces(cells, options.code_stretch), title, repo, line_count(text), len(cells))
    if b"\0" in data[:8000]:
        raise LeftOut("not text")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = data.decode("latin-1")
    text = text.replace("\r\n", "\n")
    check(text, source=rules.ext_of(path) in rules.SOURCE_EXTENSIONS)
    return CodeFile(lines(text, options.code_stretch), title, repo, line_count(text), None)


def check(text: str, source: bool) -> None:
    if PRIVATE_KEY.search(text):
        raise LeftOut("holds a private key")
    if not source:
        return
    top = text[:1000]
    for mark in ("DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol",
                 "<auto-generated"):
        if mark in top:
            raise LeftOut(f"made by a program (“{mark}”)")
    n = max(1, line_count(text))
    if len(text) // n > 300 and any(len(l) > 3000 for l in text.split("\n")):
        raise LeftOut(f"minified ({len(text) // n} characters a line)")


def line_count(text: str) -> int:
    count = text.count("\n")
    return count if text.endswith("\n") or not text else count + 1


def lines(text: str, size: int = 1800) -> list[Piece]:
    """Stretches of whole lines, at most `size` characters, ending where the code does when it can (a new block at the
    left margin, a blank line) in their last 60%. One cut mid-block hands its last two lines to the next."""
    all_lines = text.replace("\r\n", "\n").split("\n")
    if all_lines and all_lines[-1] == "":
        all_lines.pop()
    count = len(all_lines)
    offsets = [0]
    for line in all_lines:
        offsets.append(offsets[-1] + len(line) + 1)

    def blank(i: int) -> bool:
        return not all_lines[i].strip()

    def starts_block(i: int) -> bool:
        line = all_lines[i]
        if not line or line[0].isspace():
            return False
        return line[0] not in "})]" and line.strip() not in CLOSERS

    pieces: list[Piece] = []
    start = 0
    while start < count:
        while start < count and blank(start):
            start += 1
        if start >= count:
            break
        end = start + 1
        while end < count and offsets[end + 1] - offsets[start] <= size:
            end += 1
        natural = end >= count
        if not natural:
            floor = offsets[start] + size * 2 // 5

            def last_break(is_break) -> int | None:
                line = end
                while line > start + 1 and offsets[line] >= floor:
                    if is_break(line):
                        return line
                    line -= 1
                return None

            cut = last_break(lambda l: starts_block(l) and blank(l - 1))
            if cut is None:
                cut = last_break(lambda l: blank(l - 1) or starts_block(l))
            if cut is not None:
                end, natural = cut, True
        last = end
        while last > start + 1 and blank(last - 1):
            last -= 1
        body = "\n".join(all_lines[start:last])[:LONGEST_PIECE]
        pieces.append(Piece(body, start + 1, last))
        start = end if natural else max(end - 2, start + 1)
    return pieces


def notebook_cells(data: bytes) -> list[str]:
    try:
        notebook = json.loads(data)
    except ValueError as error:
        raise ValueError("not a notebook") from error
    cells = notebook.get("cells")
    if cells is None:
        cells = (notebook.get("worksheets") or [{}])[0].get("cells", [])
    out = []
    for cell in cells:
        source = cell.get("source", cell.get("input", ""))
        out.append("".join(source) if isinstance(source, list) else str(source))
    return out


def cells_to_pieces(cells: list[str], size: int = 1800) -> list[Piece]:
    pieces: list[Piece] = []
    text, first, last = "", 0, 0

    def flush():
        nonlocal text
        if text:
            pieces.append(Piece(text, first, last))
            text = ""

    for index, cell in enumerate(cells):
        body = cell.strip()
        if not body:
            continue
        number = index + 1
        if len(body) > size:
            flush()
            pieces += [Piece(p.text, number, number) for p in lines(body, size)]
            continue
        if text and len(text) + 2 + len(body) > size:
            flush()
        if not text:
            first, text = number, body
        else:
            text += "\n\n" + body
        last = number
    flush()
    return pieces


def place(path: str) -> tuple[str | None, str]:
    """The repo a file is in, and its title: its path from the repo's parent ("billing/payments/retry.py")."""
    home = str(Path.home()).lower()
    folder = os.path.dirname(path)
    repo = None
    while len(folder) > 3 and folder.lower() != home:
        if os.path.exists(os.path.join(folder, ".git")) or rules.is_project_root(folder):
            repo = folder
            break
        parent = os.path.dirname(folder)
        if parent == folder:
            break
        folder = parent
    if repo:
        parent = os.path.dirname(repo)
        return repo, path[len(parent) + 1:].replace("\\", "/")
    parts = Path(path).parts
    return None, "/".join(parts[-2:])


def summary(text: str) -> str:
    """A stretch in one line: its first line that defines something, else its first line of code."""
    rows = [l.strip() for l in text.split("\n") if l.strip()]
    definition = next((l for l in rows if any(defines_something(w) for w in l.split()[:4])), None)
    code = next((l for l in rows if not l.startswith(("//", "#", "/*", "*", "--", '"""', "import ", "from ",
                                                       "#include", "using ", "package ", "}", ")", "@"))), None)
    line = definition or code or (rows[0] if rows else "")
    return line[:160] + "…" if len(line) > 160 else line


