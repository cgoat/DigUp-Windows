def language(path: str) -> str:
    name = os.path.basename(path)
    ext = rules.ext_of(path)
    if ext in LANGUAGES:
        return LANGUAGES[ext]
    if name in rules.CODE_FILE_NAMES or name.startswith("Dockerfile"):
        return name
    return ext.upper() if ext else "Text"


# MARK: Names in code

DEFINERS = {
    "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
    "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
    "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*",
    "Function", "Sub",
}
USERS = {
    "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
    "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
}
COMMENT_STARTS = ("//", "#", "/*", "*", "--", '"""', "'''", "<!--", ";", "REM ", "::")
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$")


def identifier(query: str) -> list[str] | None:
    """The words keyword search keeps a name from code as, when the query is one (snake_case, camelCase, dotted, with
    digits). None for words anyone would say."""
    name = query.strip()
    if name.endswith("()"):
        name = name[:-2]
    if not _IDENT.match(name):
        return None
    camel = any(c.isupper() for c in name[1:]) and any(c.islower() for c in name)
    if not (camel or any(c in "_.:#$" or c.isdigit() for c in name)):
        return None
    return [w for w in re.split(r"[^0-9a-z]+", name.lower()) if w]


def phrase(words: list[str]) -> str:
    return '"' + " ".join(words) + '"'


def defines_something(word: str) -> bool:
    return word in DEFINERS and word not in ("let", "var", "const", "val")


def _strength(before: str, after: str, line: str) -> int:
    previous = before.split()[-1] if before.split() else ""
    if previous in DEFINERS:
        return 2
    if before.startswith("func (") and before.endswith(")"):
        return 2
    if before.startswith(("- (", "+ (")):
        return 2 if after.startswith((":", "{", ";")) or not after else 0
    if not after.startswith("(") or not before or previous in USERS:
        return 0
    if any(c in "=(,.!?" for c in before) or "->" in before:
        return 0
    last = before[-1]
    if not (last.isalnum() or last in "*&>_]"):
        return 0
    return 1 if line.strip().endswith(";") else 2


def _occurrences(name: str, line: str) -> list[tuple[int, int]]:
    found = []
    low, needle = line.lower(), name.lower()
    start = 0
    while (i := low.find(needle, start)) >= 0:
        j = i + len(needle)
        clear_before = i == 0 or not (line[i - 1].isalnum() or line[i - 1] in "_$")
        clear_after = j == len(line) or not (line[j].isalnum() or line[j] in "_$")
        if clear_before and clear_after:
            found.append((i, j))
        start = j
    return found


def definition(name: str, text: str, first: int) -> tuple[int, int] | None:
    """(line, strength) where `name` is defined in `text` (whose first line is `first`), or None."""
    best = None
    for offset, line in enumerate(text.split("\n")):
        for a, b in _occurrences(name, line):
            strength = _strength(line[:a].strip(), line[b:].strip(), line)
            if strength > (best[1] if best else 0):
                best = (first + offset, strength)
            if strength == 2:
                return best
    return best


def _has(word: str, line: str) -> bool:
    low = line.lower()
    start = 0
    while (i := low.find(word, start)) >= 0:
        if i == 0 or not low[i - 1].isalnum() or line[i].isupper():
            return True
        start = i + len(word)
    return False


def first_line(words: list[str], text: str, first: int) -> int | None:
    """The line to open at for `words`: the first that defines something, else the first of code, else the first."""
    words = [w.lower() for w in words if len(w) >= 2]
    if not words:
        return None
    first_code = first_any = None
    for offset, line in enumerate(text.split("\n")):
        if not any(_has(w, line) for w in words):
            continue
        trimmed = line.strip()
        if any(defines_something(w) for w in trimmed.split()[:4]):
            return first + offset
        if first_code is None and not trimmed.startswith(COMMENT_STARTS):
            first_code = offset
        if first_any is None:
            first_any = offset
    chosen = first_code if first_code is not None else first_any
    return None if chosen is None else first + chosen
