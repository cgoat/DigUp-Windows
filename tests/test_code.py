"""Code search: stretches of whole lines, notebook cells, names and where they're defined."""

import json

from digup import codeextract as ce


def test_short_file_is_one_stretch():
    assert [(p.text, p.first, p.last) for p in ce.lines("import os\n\ndef a():\n    pass\n\n\n")] == [
        ("import os\n\ndef a():\n    pass", 1, 4)]


def test_stretches_end_where_code_does():
    body = "\n".join(f"    value_number_{i} = compute_something({i})" for i in range(16))
    text = "\n\n".join(f"def f{n}():\n{body}" for n in range(3))
    pieces = ce.lines(text, size=800)
    assert [p.text.split("\n")[0] for p in pieces] == ["def f0():", "def f1():", "def f2():"]
    lines = text.split("\n")
    for p in pieces:
        assert "\n".join(lines[p.first - 1:p.last]) == p.text
        assert len(p.text) <= 800


def test_a_stretch_cut_mid_block_hands_on_two_lines():
    text = "def big():\n" + "\n".join(f"    value_{i} = compute({i})" for i in range(101))
    pieces = ce.lines(text, size=600)
    assert len(pieces) > 2
    for p, nxt in zip(pieces, pieces[1:]):
        assert nxt.first == p.last - 1
    assert pieces[-1].last == 102


def test_notebook_cells():
    nb = {"cells": [
        {"cell_type": "markdown", "source": ["# Class balance\n"]},
        {"cell_type": "code", "source": "counts = df.label.value_counts()",
         "outputs": [{"data": {"image/png": "AAAA"}}]},
        {"cell_type": "code", "source": ""},
        {"cell_type": "code", "source": ["counts.plot.bar()"]},
    ]}
    cells = ce.notebook_cells(json.dumps(nb).encode())
    assert len(cells) == 4 and "AAAA" not in "".join(cells)
    pieces = ce.cells_to_pieces(cells)
    assert len(pieces) == 1 and (pieces[0].first, pieces[0].last) == (1, 4)
    assert pieces[0].text.startswith("# Class balance\n\ncounts")


def test_identifiers_and_definitions():
    assert ce.identifier("refreshAccessToken") == ["refreshaccesstoken"]
    assert ce.identifier("quantize_row_q8_0_ref") == ["quantize", "row", "q8", "0", "ref"]
    assert ce.identifier("os.path.join()") == ["os", "path", "join"]
    assert ce.identifier("retry") is None and ce.identifier("retry with backoff") is None
    text = "token = refresh_token(user)\n\ndef refresh_token(user):\n    return api.refresh(user)"
    assert ce.definition("refresh_token", text, first=10) == (12, 2)
    c = "int n = count_rows(t);\nstatic int count_rows(struct table * t) {"
    assert ce.definition("count_rows", c, first=1) == (2, 2)
    assert ce.definition("count_rows", "int count_rows(struct table * t);", first=1) == (1, 1)
    assert ce.first_line(["retry"], "# retry later\nx = 1\ndef retry_with_backoff():\n", first=5) == 7


def test_keys_and_generated_code_are_left_out(tmp_path):
    key = "-----BEGIN RSA PRIVATE KEY-----\n" + "A" * 64 + "\n-----END RSA PRIVATE KEY-----\n"
    f = tmp_path / "deploy.py"
    f.write_text(f'KEY = """{key}"""\n')
    try:
        ce.read(str(f), ce.IndexOptions())
        raise AssertionError("a file with a private key was read")
    except ce.LeftOut:
        pass
    # Code that only mentions the marker (like this project's own check) is fine.
    f.write_text('if "PRIVATE KEY-----" in text:\n    raise LeftOut()\n')
    assert ce.read(str(f), ce.IndexOptions()).pieces
    f.write_text("// Code generated by protoc. DO NOT EDIT.\nint x;\n")
    try:
        ce.read(str(f.with_suffix(".py")) if False else str(f), ce.IndexOptions())
        raise AssertionError("generated code was read")
    except ce.LeftOut:
        pass
